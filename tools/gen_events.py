#!/usr/bin/env python3
"""Generate src/qt_events_gen.{h,c} from the "Current Trace Events and Data" table
of the QNX SDP 8.0 System Analysis Toolkit guide, saved as plain text.

The table itself is QNX documentation and is not redistributed here; only the
facts derived from it (event names, argument names and their widths) are.

usage: gen_events.py <table.txt> <outdir>
"""
import re
import sys


def parse(path):
    blocks, cur, field = [], None, None
    for raw in open(path, encoding='utf-8'):
        line = raw.rstrip('\n').strip()
        m = re.match(r'^(Class|Event|Fast|Wide|Call|#Args):\s*(.*)$', line)
        if m:
            key, val = m.groups()
            if key == 'Class':
                cur = {'Class': val}
                blocks.append(cur)
            elif cur is not None:
                cur[key] = val
            field = key
        elif cur is not None and field in ('Fast', 'Wide') and line and not line.startswith(('Note', '#')):
            cur[field] += ' ' + line
    return [b for b in blocks if 'Event' in b]


def args(s):
    if s is None or s.strip() in ('', 'N/A'):
        return []
    out = []
    for a in [x.strip() for x in s.split(',') if x.strip()]:
        w = 2 if '(64)' in a else 1
        name = a.replace('(64)', '').strip()
        name = re.sub(r'[^A-Za-z0-9_\[\]>.-]+', '_', name).strip('_') or 'arg'
        out.append((name, w))
    return out


# Names the documentation table spells differently from <sys/kercalls.h> in SDP 8.0
# (found by the first build against the SDP): the 64-bit enter and the exit rows of
# SyncTypeDestroy() say __KER_TYPE_SYNC_DESTROY, the header has __KER_SYNC_TYPE_DESTROY.
DOC_NAME_FIXES = {'TYPE_SYNC_DESTROY': 'SYNC_TYPE_DESTROY'}

# Kernel calls in <sys/kercalls.h> (SDP 8.0) that the table has no row for, with the
# library function that makes each one (<sys/neutrino.h>). Their arguments are not
# documented, so qtrace shows them by name and return value only. TEST and SYS_CUSTOM
# have no public wrapper.
EXTRA_KCALLS = [
    ('MSG_RECEIVEPULSEV', 'MsgReceivePulse'),
    ('CONNECT_DUPFD', 'ConnectDupFd'),
    ('INTERRUPT_UNBLOCK', 'InterruptUnblock'),
    ('INTERRUPT_CTL', 'InterruptCtl'),
    ('PIPE_OPEN', 'PipeOpen'),
    ('PIPE_CTL', 'PipeCtl'),
    ('PIPE_CLOSE', 'PipeClose'),
    ('TEST', 'KerTest'),
    ('SYS_CUSTOM', 'SysCustom'),
]


def main(table, outdir):
    blocks = parse(table)
    kcalls, kdesc, events = [], [], []
    seen_k, seen_e = set(), set()
    for b in blocks:
        cls, ev = b['Class'], b['Event']
        is64 = '_NTO_TRACE_KERCALL64' in ev
        ev = ev.split('|')[0].strip()
        if cls.startswith('_NTO_TRACE_KERCALL'):
            k = ev.replace('__KER_', '')
            k = DOC_NAME_FIXES.get(k, k)
            if k not in seen_k:
                seen_k.add(k)
                call = (b.get('Call') or '').split(',')[0].strip()
                if not call or call in ('N/A', '—') or ' ' in call:
                    call = k.title().replace('_', '')
                kcalls.append((k, call))
            kdesc.append((k, cls.endswith('EXIT'), is64, args(b.get('Fast')), args(b.get('Wide'))))
        else:
            name = re.sub(r'[^A-Za-z0-9_]+', '_', ev.replace('_NTO_TRACE_', '')).strip('_')
            if (cls, name) in seen_e:
                continue
            seen_e.add((cls, name))
            events.append((cls.replace('_NTO_TRACE_', ''), name, args(b.get('Fast')), args(b.get('Wide'))))
    for k, call in EXTRA_KCALLS:
        if k in seen_k:
            sys.exit('gen_events.py: %s is in the table now: drop it from EXTRA_KCALLS' % k)
        seen_k.add(k)
        kcalls.append((k, call))

    h = ['/* Generated by tools/gen_events.py from the QNX SDP 8.0 SAT event table - do not edit. */',
         '#ifndef QT_EVENTS_GEN_H', '#define QT_EVENTS_GEN_H', '', 'enum qt_kcall {']
    h += ['    QT_K_%s,' % k for k, _ in kcalls] + ['    QT_K__COUNT', '};', '', 'enum qt_evid {']
    h += ['    QT_E_%s,' % n for _, n, _, _ in events] + ['    QT_E__COUNT', '};', '']
    h += ['typedef struct { const char *name; unsigned char words; } qt_arg_t;',
          'typedef struct {',
          '    int k; unsigned char exit, is64, nfast, nwide;',
          '    const qt_arg_t *fast, *wide;',
          '} qt_kdesc_t;',
          'typedef struct {',
          '    const char *cls, *name; unsigned char nfast, nwide;',
          '    const qt_arg_t *fast, *wide;',
          '} qt_edesc_t;',
          'extern const char *const qt_kcall_name[QT_K__COUNT];   /* e.g. "MSG_SENDV" */',
          'extern const char *const qt_kcall_func[QT_K__COUNT];   /* e.g. "MsgSend"   */',
          'extern const qt_kdesc_t qt_kdesc[];',
          'extern const unsigned qt_nkdesc;',
          'extern const qt_edesc_t qt_edesc[QT_E__COUNT];', '',
          '/* X-macros: the QNX adapter maps SDP header constants to these ids. */',
          '#define QT_FOR_EACH_KCALL(X) \\']
    h += ['    X(%s) \\' % k for k, _ in kcalls] + ['', '#define QT_FOR_EACH_EVENT(X) \\']
    h += ['    X(%s, %s) \\' % (c, n) for c, n, _, _ in events] + ['', '#endif', '']

    c = ['/* Generated by tools/gen_events.py - do not edit. */', '#include "qt_events_gen.h"', '']
    c += ['const char *const qt_kcall_name[QT_K__COUNT] = {'] + ['    "%s",' % k for k, _ in kcalls] + ['};']
    c += ['const char *const qt_kcall_func[QT_K__COUNT] = {'] + ['    "%s",' % f for _, f in kcalls] + ['};', '']

    def arr(name, lst):
        if not lst:
            return 'static const qt_arg_t %s[1] = {{0, 0}};' % name
        return 'static const qt_arg_t %s[] = {%s};' % (name, ', '.join('{"%s", %d}' % a for a in lst))

    rows = []
    for i, (k, is_exit, is64, fa, wa) in enumerate(kdesc):
        c.append(arr('kf%d' % i, fa))
        c.append(arr('kw%d' % i, wa))
        rows.append('    {QT_K_%s, %d, %d, %d, %d, kf%d, kw%d},' % (k, is_exit, is64, len(fa), len(wa), i, i))
    c += ['', 'const qt_kdesc_t qt_kdesc[] = {'] + rows + ['};', 'const unsigned qt_nkdesc = %d;' % len(kdesc), '']
    rows = []
    for i, (cls, n, fa, wa) in enumerate(events):
        c.append(arr('ef%d' % i, fa))
        c.append(arr('ew%d' % i, wa))
        rows.append('    {"%s", "%s", %d, %d, ef%d, ew%d},' % (cls, n, len(fa), len(wa), i, i))
    c += ['', 'const qt_edesc_t qt_edesc[QT_E__COUNT] = {'] + rows + ['};', '']
    with open(outdir + '/qt_events_gen.h', 'w') as f:
        f.write('\n'.join(h))
    with open(outdir + '/qt_events_gen.c', 'w') as f:
        f.write('\n'.join(c))
    with open(outdir + '/qt_kcalls_qnx.h', 'w') as f:
        f.write('/* Generated by tools/gen_events.py - do not edit.\n'
                ' * One K(name) per kernel call, for code that has <sys/kercalls.h>. */\n')
        f.write(''.join('K(%s)\n' % k for k, _ in kcalls))
    print('%d kernel calls, %d kernel-call descriptors, %d other events' % (len(kcalls), len(kdesc), len(events)))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
