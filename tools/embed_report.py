#!/usr/bin/env python3
"""Embed report/template.html into src/qt_report_tpl.c (split at the data placeholder)."""
import sys

src, dst = sys.argv[1], sys.argv[2]
html = open(src, encoding='utf-8').read()
head, tail = html.split('/*QTRACE_DATA*/')


def c_string(s):
    out = []
    for line in s.splitlines(keepends=True):
        esc = line.encode('utf-8').decode('latin-1')
        esc = esc.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n')
        esc = ''.join(ch if 32 <= ord(ch) < 127 else '\\%03o' % ord(ch) for ch in esc)
        out.append('    "%s"' % esc)
    return '\n'.join(out) or '    ""'


with open(dst, 'w') as f:
    f.write('/* Generated by tools/embed_report.py from report/template.html - do not edit. */\n')
    f.write('const char qt_report_head[] =\n%s;\n' % c_string(head))
    f.write('const char qt_report_tail[] =\n%s;\n' % c_string(tail))
